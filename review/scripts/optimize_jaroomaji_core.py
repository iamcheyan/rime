def load_mozc() -> dict[str, list[str]]:
    """word -> [codes]，用于交叉验证。"""
    if not MOZC_CROSSCHECK.exists():
        return {}
    m: dict[str, list[str]] = {}
    with MOZC_CROSSCHECK.open(encoding="utf-8") as fh:
        for line in fh:
            cols = line.rstrip("\n").split("\t")
            if len(cols) == 3 and not cols[0].startswith("#"):
                m.setdefault(cols[0], []).append(cols[1])
    return m


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    mozc = load_mozc()
    seen: set[tuple[str, str]] = set()
    rows: list[str] = []
    dup_in_list = 0
    cross_total = cross_match = 0
    mismatches: list[str] = []

    for word, reading, cat in WORDS:
        code = to_romaji(reading)
        key = (word, code)
        if key in seen:
            dup_in_list += 1
            continue
        seen.add(key)
        rows.append(f"{word}\t{code}\t{WEIGHT[cat]}")
        if word in mozc:
            cross_total += 1
            if code in mozc[word]:
                cross_match += 1
            else:
                mismatches.append(f"{word}: ours={code!r} mozc={mozc[word]!r}")

    print(f"entries={len(rows)} dup_in_list={dup_in_list}")
    print(
        f"mozc cross-check: {cross_match}/{cross_total} 完全一致 "
        f"(mozc 中不存在的词 {len(rows) - cross_total} 条仅按标准罗马字生成)"
    )
    for m in mismatches:
        print(f"  MISMATCH {m}")

    if args.apply:
        text = TARGET.read_text(encoding="utf-8")
        if text.rstrip().endswith("..."):
            marker_idx = text.rindex("...")
            head = text[: marker_idx + 3]
            body = "\n\n# ---- 核心常用词（dict-optimize 生成，Nihon-shiki 码，与 mozc 表交叉验证）----\n"
            body += "\n".join(rows) + "\n"
            TARGET.write_text(head + body, encoding="utf-8")
            print(f"applied -> {TARGET} (+{len(rows)} entries)")
        else:
            print("ERROR: jaroomaji.dict.yaml 结构与预期不符，未写入", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
