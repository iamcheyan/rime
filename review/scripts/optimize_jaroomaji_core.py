KATA2HIRA = {chr(ord("ァ") + i): chr(ord("ぁ") + i) for i in range(86)}

def to_romaji(reading: str) -> str:
    """假名读音(平/片假名混在) → mozc 风格空格分隔 Nihon-shiki 码。"""
    s = "".join(KATA2HIRA.get(c, c) for c in reading)
    out: list[str] = []
    i = 0
    while i < len(s):
        two = s[i : i + 2]
        if two in DIGRAPHS:
            out.append(DIGRAPHS[two])
            i += 2
            continue
        one = s[i]
        if one == "ー":
            out.append("-")
        elif one in MONOGRAPHS:
            out.append(MONOGRAPHS[one])
        elif one == "・":
            pass
        else:
            raise ValueError(f"未处理的字符 {one!r} (读音 {reading!r})")
        i += 1
    return " ".join(out)


