def derive_codes(text: str) -> list[str]:
    """计算词条的标准 4 码公式与全双拼编码"""
    sp_list = [get_char_shuangpin(c) for c in text]
    if any(sp is None for sp in sp_list):
        return []

    n = len(text)
    codes = []

    # 1. 计算 4 码公式
    if n == 2:
        codes.append(sp_list[0] + sp_list[1])
    elif n == 3:
        # 声1 + 声2 + 声3 + 韵3
        c4 = sp_list[0][0] + sp_list[1][0] + sp_list[2][0] + sp_list[2][1]
        codes.append(c4)
    elif n >= 4:
        # 声1 + 声2 + 声3 + 末声
        c4 = sp_list[0][0] + sp_list[1][0] + sp_list[2][0] + sp_list[-1][0]
        codes.append(c4)

    # 2. 全双拼编码
    full_sp = "".join(sp_list)
    if full_sp not in codes:
        codes.append(full_sp)

    return codes


